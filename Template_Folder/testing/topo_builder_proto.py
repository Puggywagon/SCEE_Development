"""Prototype: build a .gro whose atom order is taken from a GROMACS .itp.

Atoms and bonds come from the topology; the SMILES string is only used to
assign bond orders (single/double/aromatic). Coordinates are generated by
RDKit, so the output order matches the topology by construction.
"""
import re, sys
from rdkit import Chem
from rdkit.Chem import AllChem

MASS_TO_ELEMENT = [(1.008, 'H'), (12.011, 'C'), (14.007, 'N'), (15.999, 'O'),
                   (18.998, 'F'), (32.06, 'S'), (35.45, 'Cl'), (79.90, 'Br')]
# united-atom carbons: CH (13.019), CH2 (14.027), CH3 (15.035), CH4 (16.043)
UA_CARBON = {13.019: 1, 14.027: 2, 15.035: 3, 16.043: 4}

def sections(path):
    out, cur = {}, None
    for line in open(path):
        text = line.split(';')[0].strip()
        if not text:
            continue
        m = re.match(r'\[\s*(\w+)\s*\]', text)
        if m:
            cur = m.group(1).lower(); out.setdefault(cur, []); continue
        if cur:
            out[cur].append(text.split())
    return out

def element_and_h(name, mass):
    """Element symbol and number of implicit (united-atom) hydrogens."""
    for m, n_h in UA_CARBON.items():
        if abs(mass - m) < 0.01:
            return 'C', n_h
    best = min(MASS_TO_ELEMENT, key=lambda x: abs(x[0] - mass))
    if abs(best[0] - mass) < 0.6:
        return best[1], 0
    raise ValueError(f'Cannot identify element for atom {name} (mass {mass})')

def build(itp, smiles, out_gro, resname='MOL'):
    sec = sections(itp)
    atoms = sec['atoms']
    rw = Chem.RWMol()
    names, implicit_h = [], []
    for a in atoms:
        name, mass = a[4], float(a[7])
        el, n_h = element_and_h(name, mass)
        atom = Chem.Atom(el)
        atom.SetNoImplicit(True)
        rw.AddAtom(atom); names.append(name); implicit_h.append(n_h)
    for b in sec.get('bonds', []) + sec.get('constraints', []):
        i, j = int(b[0]) - 1, int(b[1]) - 1
        if rw.GetBondBetweenAtoms(i, j) is None:
            rw.AddBond(i, j, Chem.BondType.SINGLE)
    n_top = rw.GetNumAtoms()
    # united atoms: temporarily add their hydrogens so the geometry is right
    for idx, n_h in enumerate(implicit_h):
        for _ in range(n_h):
            h = rw.AddAtom(Chem.Atom('H')); rw.AddBond(idx, h, Chem.BondType.SINGLE)
    mol = rw.GetMol()
    template = Chem.AddHs(Chem.MolFromSmiles(smiles))
    mol = AllChem.AssignBondOrdersFromTemplate(template, mol)
    Chem.SanitizeMol(mol)
    if AllChem.EmbedMolecule(mol, randomSeed=42) != 0:
        raise RuntimeError('3D embedding failed')
    AllChem.MMFFOptimizeMolecule(mol)
    conf = mol.GetConformer()
    with open(out_gro, 'w') as f:
        f.write(f'{resname} built from {itp} (topology order)\n{n_top}\n')
        for i in range(n_top):               # only the topology's own atoms
            p = conf.GetAtomPosition(i) / 10.0
            f.write(f'{1:5d}{resname:<5s}{names[i]:>5s}{i+1:5d}{p.x:8.3f}{p.y:8.3f}{p.z:8.3f}\n')
        f.write(f'{0.0:10.5f}{0.0:10.5f}{0.0:10.5f}\n')
    return mol, n_top

if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2], sys.argv[3])
